// Writes the shared rules (js/rng.js, js/rules.js, js/ai.js) into server.js
// between its `// RULES:BEGIN` and `// RULES:END` markers. The platform runs
// server.js as one classic script (no imports), so each ES module becomes a
// function scope whose exports form an object (`Rng`, `Rules`, `Ai`); its
// imports read those objects. (After crown-draughts' tools/build-server.mjs.)
//
//   node tools/build-server.mjs          rewrite the block
//   node tools/build-server.mjs --check  exit 1 when the block is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const MODULES = [
  { name: 'Rng', file: 'js/rng.js' },
  { name: 'Rules', file: 'js/rules.js' },
  { name: 'Ai', file: 'js/ai.js' },
];
const BY_FILE = { './rng.js': 'Rng', './rules.js': 'Rules', './ai.js': 'Ai' };

function convert({ name, file }) {
  let src = readFileSync(ROOT + file, 'utf8');
  const exported = [];
  src = src.replace(/^import \{([^}]*)\} from '([^']+)';$/gm, (_, names, from) => {
    const mod = BY_FILE[from];
    if (!mod) throw new Error(`${file}: unknown import ${from}`);
    return `const {${names}} = ${mod};`;
  });
  src = src.replace(/^export (const|let|function|class) ([A-Za-z_$][\w$]*)/gm, (_, kind, id) => {
    exported.push(id);
    return `${kind} ${id}`;
  });
  if (/^\s*(import|export)\b/m.test(src)) throw new Error(`${file}: an import/export the build does not handle`);
  return `var ${name} = (function () {\n${src.trim()}\nreturn { ${exported.join(', ')} };\n})();`;
}

function rulesBlock() {
  return [
    '// RULES:BEGIN — generated by tools/build-server.mjs from js/{rng,rules,ai}.js; do not edit.',
    ...MODULES.map(convert),
    '// RULES:END',
  ].join('\n');
}

const file = ROOT + 'server.js';
const cur = readFileSync(file, 'utf8');
const a = cur.indexOf('// RULES:BEGIN'), b = cur.indexOf('// RULES:END');
if (a < 0 || b < 0) throw new Error('server.js has no RULES block');
const next = cur.slice(0, a) + rulesBlock() + cur.slice(b + '// RULES:END'.length);
if (process.argv.includes('--check')) {
  if (next !== cur) { console.error('server.js: the RULES block is stale — run node tools/build-server.mjs'); process.exit(1); }
  console.log('server.js: RULES block current');
} else if (next !== cur) {
  writeFileSync(file, next);
  console.log('server.js: RULES block written');
} else console.log('server.js: RULES block current');
